/* Helper: Ambil teks sesuai bahasa aktif (fallback aman untuk kiriman komunitas) */
export function getLocalizedField(item, field, lang) {
  if (!item) return '';
  if (lang === 'en') {
    const enValue = item[`${field}En`];
    if (enValue !== undefined && enValue !== null && enValue !== '') return enValue;
  }
  return item[field] ?? '';
}

/* Helper: Gabungkan data localStorage lama dengan terjemahan bawaan terbaru tanpa menghapus kontribusi user */
export function hydrateCheats(savedList) {
  if (!Array.isArray(savedList) || savedList.length === 0) return INITIAL_CHEATS;
  const defaultsMap = new Map(INITIAL_CHEATS.map((item) => [item.id, item]));
  const merged = savedList.map((saved) => {
    const base = defaultsMap.get(saved.id);
    if (!base) return saved;
    return {
      ...base,
      ...saved,
      nameEn: saved.nameEn || base.nameEn,
      requirementEn: saved.requirementEn || base.requirementEn,
      authorEn: saved.author === 'Arsip Global VI' ? base.authorEn : saved.authorEn || saved.author,
    };
  });
  const existingIds = new Set(merged.map((m) => m.id));
  const missingDefaults = INITIAL_CHEATS.filter((item) => !existingIds.has(item.id));
  return [...merged, ...missingDefaults];
}

